import assert from 'node:assert/strict';
import sharp from 'sharp';
import { zipSync, unzipSync } from 'fflate';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE);
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'] });
const baseURL = process.env.DASHBOARD_TEST_URL;
const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 }, colorScheme: 'dark', extraHTTPHeaders: { 'x-forwarded-proto': 'https' } });
const [name, ...parts] = process.env.DASHBOARD_TEST_COOKIE.split('=');
await context.addCookies([{ name, value: parts.join('='), url: baseURL, httpOnly: true, sameSite: 'Lax' }]);
await context.route('**/api/**', async route => {
  if (route.request().method() === 'GET') return route.continue();
  const response = await route.fetch({ headers: { ...route.request().headers(), origin: 'https://live.example.test' } }); await route.fulfill({ response });
});
const page = await context.newPage(), errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto('/#canvas/canvas-layout', { waitUntil: 'domcontentloaded' });
  await page.locator('#canvas-settings .canvas-row').first().waitFor();
  // Changing only monochrome must update the existing iframe immediately.
  await page.locator('#canvas-widgets [data-widget-id="backdrop"] .canvas-row-main').click();
  const backdrop = page.locator('.canvas-preview [data-widget-id="backdrop"] iframe');
  await page.locator('#canvas-field-monochrome').check();
  await page.waitForFunction(() => new URL(document.querySelector('.canvas-preview [data-widget-id="backdrop"] iframe').src).searchParams.get('monochrome') === '1');
  await page.locator('#canvas-field-monochrome').uncheck();
  await page.waitForFunction(() => !new URL(document.querySelector('.canvas-preview [data-widget-id="backdrop"] iframe').src).searchParams.has('monochrome'));
  assert.equal(await backdrop.count(), 1, 'one iframe is reused across color toggles');
  // Keep a list control focused, then select/drag on the preview at mobile size.
  // Rebuilding the list must not refocus it below the canvas.
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#canvas-widgets [data-widget-id="cat"] .canvas-row-main').click();
  await page.locator('.canvas-preview').scrollIntoViewIfNeeded();
  await page.waitForTimeout(100);
  const scrollState = () => page.evaluate(() => [window.scrollY, ...[...document.querySelectorAll('.content')].map(el => el.scrollTop)]);
  const scrollBefore = await scrollState();
  const avatar = page.locator('.canvas-preview [data-widget-id="avatar"]');
  let rect = await avatar.boundingBox();
  await page.mouse.click(rect.x + rect.width / 2, rect.y + rect.height / 2);
  assert.deepEqual(await scrollState(), scrollBefore, 'preview selection does not scroll to properties');
  assert.equal(await page.locator('#canvas-widgets [data-widget-id="avatar"] .canvas-row-main').getAttribute('aria-pressed'), 'true');
  assert.match(await page.locator('#canvas-editor-title').textContent(), /avatar/i);
  assert.equal(await page.evaluate(() => !!document.activeElement.closest('#canvas-editor, #canvas-widgets')), false, 'preview owns focus after selection');
  rect = await avatar.boundingBox();
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2); await page.mouse.down();
  await page.mouse.move(rect.x + rect.width / 2 - 10, rect.y + rect.height / 2 + 6, { steps: 4 }); await page.mouse.up();
  assert.deepEqual(await scrollState(), scrollBefore, 'preview dragging does not scroll to properties');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('.canvas-preview').scrollIntoViewIfNeeded();
  const widget = page.locator('.canvas-preview [data-widget-id="avatar"]');
  await widget.waitFor(); const before = await widget.boundingBox();
  await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2);
  await page.mouse.down(); await page.mouse.move(before.x + before.width / 2 - 50, before.y + before.height / 2 + 20, { steps: 6 }); await page.mouse.up();
  assert.ok((await widget.boundingBox()).x < before.x - 30, 'preview drag changes the draft position');
  const moved = await widget.boundingBox(), handle = await widget.locator('.preview-resize').boundingBox();
  await page.mouse.move(handle.x + 7, handle.y + 7); await page.mouse.down(); await page.mouse.move(handle.x + 40, handle.y + 30, { steps: 6 }); await page.mouse.up();
  assert.ok((await widget.boundingBox()).width > moved.width + 15, 'preview corner changes the draft size');
  await page.locator('#canvas-field-blinkInterval').fill('2.5'); await page.locator('#canvas-field-blinkInterval').blur();
  await page.locator('#canvas-save').click();
  await page.waitForFunction(() => document.querySelector('.canvas-status')?.textContent.includes('Layout saved'));
  const saved = await page.evaluate(() => fetch('/api/scene/layout').then(r => r.json()));
  assert.equal(saved.layout.widgets.find(w => w.id === 'avatar').props.blinkInterval, 2.5);
  await page.locator('#canvas-add-type').selectOption('text'); await page.locator('#canvas-draw').click();
  const preview = await page.locator('.canvas-preview').boundingBox();
  const count = await page.locator('.canvas-row').count();
  await page.mouse.move(preview.x + 20, preview.y + 40); await page.mouse.down(); await page.mouse.move(preview.x + 120, preview.y + 100, { steps: 6 }); await page.mouse.up();
  assert.equal(await page.locator('.canvas-row').count(), count + 1);
  await page.goto('/#canvas/avatar-library', { waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Avatar resources' }).waitFor();
  const png = await sharp({ create: { width: 20, height: 20, channels: 4, background: '#ee3388' } }).png().toBuffer();
  await page.getByLabel('Avatar ZIP', { exact: true }).setInputFiles({ name: 'fixture.zip', mimeType: 'application/zip', buffer: Buffer.from(zipSync({ 'idle.png': png, 'blink.png': png })) });
  await page.getByRole('button', { name: 'Upload ZIP', exact: true }).click();
  await page.getByRole('heading', { name: 'Uploaded avatar', exact: true }).waitFor();
  const packs = await page.evaluate(() => fetch('/api/avatars').then(r => r.json()));
  const pack = packs.avatars.find(p => p.name === 'Uploaded avatar'); assert.ok(pack.states.idle);
  const response = await context.request.get(`/api/admin/avatars/${pack.id}/download`);
  assert.equal(response.status(), 200); assert.ok(unzipSync(new Uint8Array(await response.body()))['idle.png']);
  let refreshes = 0;
  await page.route('**/api/admin/metrics/summary?*', async route => {
    if (new URL(route.request().url()).searchParams.get('refresh') === '1') refreshes++;
    await route.fulfill({ json: { note: 'Fixture', cpa: { enabled: true }, tokens: {}, codex: { updatedAt: Date.now(), fiveHour: { remainingPercent: 62, accounts: 1, total: 1 }, week: { remainingPercent: 75, accounts: 1, total: 1 } } } });
  });
  await page.goto('/#usage/usage-summary', { waitUntil: 'domcontentloaded' });
  await page.getByText('Last updated', { exact: false }).waitFor(); assert.equal(refreshes, 1);
  assert.equal(await page.getByLabel('Automatically update quota').isChecked(), true);
  await page.getByRole('button', { name: 'Check now', exact: true }).click();
  await page.waitForTimeout(100); assert.equal(refreshes, 2);
  assert.deepEqual(errors, []);
  console.info('Canvas feature Chromium passed: monochrome on/off without changing theme, selection/drag scroll stability, pointer move/resize/draw, blink settings, ZIP upload/download, automatic quota refresh and update time.');
} finally { await browser.close(); }
