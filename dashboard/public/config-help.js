export function helpFor(key, path, value) {
  if (HELP[key]) return HELP[key];
  const scope = path.split(".").slice(0, -1).join(" → ");
  if (Array.isArray(value)) return `Entries used by ${scope || "OpenClaw"}. Add or edit each entry below; changes are applied when you save.`;
  if (value && typeof value === "object") return `Configuration for ${key} within ${scope || "OpenClaw"}. Its individual values are listed below.`;
  if (typeof value === "boolean") return `Enable or disable ${key} within ${scope || "OpenClaw"}.`;
  return `Value for ${key} within ${scope || "OpenClaw"}. The setting name is preserved so it matches the OpenClaw configuration.`;
}
