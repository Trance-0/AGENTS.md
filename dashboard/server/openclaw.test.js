import assert from "node:assert/strict";
import { mkdtemp, writeFile, readFile, readdir, rm } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import express from "express";
import test from "node:test";
import { BroadcastStore } from "./broadcast.js";
import register from "../openclaw-plugin/index.js";

test("OpenClaw owner control records hooks and excludes private session content", async () => {
  const directory = await mkdtemp(path.join(os.tmpdir(), "openclaw-stream-"));
  process.env.OIDC_ISSUER = "https://issuer.example";
  process.env.OIDC_CLIENT_ID = "test";
  process.env.OIDC_CLIENT_SECRET = "test";
  process.env.SESSION_SECRET = "test";
  process.env.OPENCLAW_STREAM_TOKEN = "stream-test-token";
  const { mountOpenClaw } = await import("./openclaw-routes.js");
  const store = new BroadcastStore(path.join(directory, "recordings"));
  const app = express(); app.use(express.json()); mountOpenClaw(app, store);
  app.use((error, _req, res, _next) => res.status(error.status || 500).json({ error: error.message }));
  const server = app.listen(0, "127.0.0.1");
  await new Promise(resolve => server.once("listening", resolve));
  const endpoint = `http://127.0.0.1:${server.address().port}`;
  const tokenFile = path.join(directory, "stream-token"); await writeFile(tokenFile, process.env.OPENCLAW_STREAM_TOKEN, { mode: 0o600 });
  const hooks = new Map(); let factory;
  const pluginConfig = { endpoint, tokenFile };
  register({ pluginConfig, logger: { warn() {} }, on: (name, handler) => hooks.set(name, handler), registerTool: handler => { factory = handler; } });
  assert.ok(hooks.has("before_model_resolve"));
  assert.equal(hooks.has("before_agent_start"), false, "legacy hook fires in two phases and duplicates start rows");
  const owner = { agentId: "main", senderIsOwner: true, sessionKey: "agent:main:owner-session" };
  const other = { agentId: "main", sessionKey: "agent:main:private-session" };
  const request = (url, body, token = process.env.OPENCLAW_STREAM_TOKEN) => fetch(endpoint + url, { method: "POST", headers: { "content-type": "application/json", authorization: `Bearer ${token}` }, body: JSON.stringify(body) });
  try {
    assert.equal(factory({ ...owner, senderIsOwner: false }), null);
    assert.equal(factory({ ...owner, agentId: "dashboard-host" }), null);
    assert.equal((await request("/api/openclaw/stream/start", { title: "Public" }, "wrong")).status, 401);
    await hooks.get("llm_input")({ model: "test-model", prompt: "private prompt" }, other);
    assert.equal(store.list(true).length, 0);
    const tool = factory(owner);
    const started = JSON.parse((await tool.execute("start", { action: "start", title: "OpenClaw stream" })).content[0].text);
    assert.equal(started.stream.origin, "openclaw");
    assert.equal(started.stream.sessionRef.length, 64);
    assert.equal(JSON.parse((await tool.execute("again", { action: "start" })).content[0].text).stream.id, started.stream.id);
    await hooks.get("before_model_resolve")({ prompt: "PRIVATE PROMPT" }, other);
    await hooks.get("llm_input")({ model: "gpt-6-astra", provider: "cpa", runId: "chatcmpl_test", prompt: "secret private prompt", systemPrompt: "secret system" }, other);
    await hooks.get("llm_output")({ model: "test-model", assistantTexts: ["PRIVATE RESPONSE"] }, other);
    await hooks.get("before_tool_call")({ toolName: "read", params: { path: "/secret-path" } }, other);
    await hooks.get("after_tool_call")({ toolName: "read", result: "SECRET RESULT", error: "SECRET ERROR", durationMs: 30 }, other);
    await hooks.get("llm_output")({ model: "test-model", assistantTexts: ["Public broadcast message"] }, owner);
    await hooks.get("llm_output")({ model: "test-model", assistantTexts: [], lastAssistant: { stopReason: "error", errorMessage: "SECRET PROVIDER ERROR" } }, owner);
    await hooks.get("agent_end")({ success: true, durationMs: 50, messages: ["PRIVATE TRANSCRIPT", "SECRET PROVIDER ERROR"] }, owner);
    const events = store.readEvents(started.stream.id);
    assert.ok(events.some(event => event.openclawEvent === "model_start" && event.provider === "cpa" && event.runId === "chatcmpl_test" && event.msg.includes("cpa/gpt-6-astra")));
    assert.equal(events.filter(event => event.openclawEvent === "agent_start").length, 1);
    assert.ok(events.some(event => event.openclawEvent === "tool_end" && event.level === "warn"));
    assert.ok(events.some(event => event.msg === "Public broadcast message"));
    assert.ok(events.some(event => event.openclawEvent === "agent_end"));
    assert.ok(events.some(event => event.openclawEvent === "model_output" && event.level === "warn"));
    const serialized = JSON.stringify(events);
    for (const secret of ["private prompt", "secret system", "PRIVATE RESPONSE", "/secret-path", "SECRET RESULT", "SECRET ERROR", "PRIVATE TRANSCRIPT", "SECRET PROVIDER ERROR"]) assert.ok(!serialized.includes(secret), secret);
    const dedup = { type: "agent_end", agentId: "main", sessionRef: started.stream.sessionRef, recordingId: started.stream.id, eventId: "event-dedup", success: true };
    assert.equal((await request("/api/openclaw/events", dedup)).status, 201);
    assert.equal((await (await request("/api/openclaw/events", dedup)).json()).duplicate, true);
    assert.equal((await request("/api/openclaw/stream/end", { recordingId: started.stream.id, sessionRef: "f".repeat(64) })).status, 409);
    assert.equal((await request("/api/openclaw/stream/summary", { recordingId: started.stream.id, sessionRef: "f".repeat(64), agentId: "dashboard-host", summary: "wrong owner" })).status, 403);
    await tool.execute("summary", { action: "summary", summary: "Current live session summary" });
    assert.equal(store.status().summary, "Current live session summary");
    assert.ok(store.readEvents(started.stream.id).some(event => event.summary === "Current live session summary"));
    await tool.execute("end", { action: "end" });
    assert.equal(store.get(started.stream.id).summary, "Current live session summary");
    assert.equal(store.get(started.stream.id).status, "ended");
    const second = store.start("Next stream");
    assert.equal((await request("/api/openclaw/events", dedup)).status, 409);
    assert.equal(store.readEvents(second.id).length, 1);
    const anotherOwner = factory({ ...owner, sessionKey: "agent:main:another-owner-session" });
    await anotherOwner.execute("summary", { action: "summary", summary: "Admin-started stream summary" });
    assert.equal(store.status().summary, "Admin-started stream summary");
    assert.equal(store.active.id, second.id);
    pluginConfig.activityDir = path.join(directory, "activity");
    const before = store.active.eventCount;
    await hooks.get("before_tool_call")({ toolName: "read", params: { path: "/workspace/example.txt" } }, other);
    await hooks.get("llm_output")({ model: "test-model", assistantTexts: ["PRIVATE RESPONSE"] }, other);
    assert.equal(store.active.eventCount, before, "file mode must not duplicate metadata over HTTP or expose private text");
    const activity = await readFile(path.join(pluginConfig.activityDir, (await readdir(pluginConfig.activityDir))[0]), "utf8");
    assert.ok(activity.includes("/workspace/example.txt"));
    assert.ok(!activity.includes("PRIVATE RESPONSE"));
  } finally {
    server.closeAllConnections(); await new Promise(resolve => server.close(resolve));
    await rm(directory, { recursive: true, force: true });
  }
});
